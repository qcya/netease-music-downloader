'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('musicBridge', Object.freeze({
  appInfo:()=>ipcRenderer.invoke('app:info'),
  openReleasePage:()=>ipcRenderer.invoke('app:release-page'),
  mediaAvailability:(ids,options)=>ipcRenderer.invoke('music:availability',ids,options),
  discovery:options=>ipcRenderer.invoke('discovery:get',options),
  discoveryPlaylist:id=>ipcRenderer.invoke('discovery:playlist',id),
  playlistOrganize:(order,name=null,id=null)=>ipcRenderer.invoke('playlists:organize',order,name,id),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: s => ipcRenderer.invoke('settings:set',s),
  chooseDirectory: () => ipcRenderer.invoke('system:choose-directory'),
  openDirectory: () => ipcRenderer.invoke('system:open-directory'),
  checkPython: () => ipcRenderer.invoke('system:python'),
  search: (q,page) => ipcRenderer.invoke('music:search',q,page),
  songInfo: id => ipcRenderer.invoke('music:song-info',id),
  download: ids => ipcRenderer.invoke('music:download',ids),
  playlist: id => ipcRenderer.invoke('music:playlist',id),
  openSong: id => ipcRenderer.invoke('music:open-song',id),
  playlistsList:()=>ipcRenderer.invoke('playlists:list'),
  playlistsAdd:(id,name)=>ipcRenderer.invoke('playlists:add',id,name),
  playlistsRemove:(id,name)=>ipcRenderer.invoke('playlists:remove',id,name),
  playlistsReorder:names=>ipcRenderer.invoke('playlists:reorder',names),
  playlistCategoriesList:()=>ipcRenderer.invoke('playlists:categories-list'),
  playlistCategoryCreate:name=>ipcRenderer.invoke('playlists:categories-create',name),
  playlistCategoryRename:(id,name)=>ipcRenderer.invoke('playlists:categories-rename',id,name),
  playlistRenameDefault:name=>ipcRenderer.invoke('playlists:rename-default',name),
  playlistCategoryDelete:id=>ipcRenderer.invoke('playlists:categories-delete',id),
  playlistCategoryMove:(name,id)=>ipcRenderer.invoke('playlists:categories-move',name,id),
  importLocal:kind=>ipcRenderer.invoke('local:import',kind),
  localLyrics:name=>ipcRenderer.invoke('local:lyrics',name),
  openMiniPlayer:()=>ipcRenderer.invoke('mini:open'),
  closeMiniPlayer:()=>ipcRenderer.invoke('mini:close'),
  updateMiniPlayer:state=>ipcRenderer.invoke('mini:state',state),
  onMiniControl:cb=>{const listener=(_e,action)=>cb(action);ipcRenderer.on('mini:control',listener);return()=>ipcRenderer.removeListener('mini:control',listener)},
  onMiniStatus:cb=>{const listener=(_e,data)=>cb(data);ipcRenderer.on('mini:status',listener);return()=>ipcRenderer.removeListener('mini:status',listener)},
  playerBackground:()=>ipcRenderer.invoke('background:get'),
  choosePlayerBackground:()=>ipcRenderer.invoke('background:choose'),
  clearPlayerBackground:()=>ipcRenderer.invoke('background:clear'),
  listFiles: () => ipcRenderer.invoke('local:list'),
  deleteLocal:(name,confirmed)=>ipcRenderer.invoke('local:delete',name,confirmed),
  downloadHistory:()=>ipcRenderer.invoke('download:history'),
  cancelDownload:id=>ipcRenderer.invoke('download:cancel',id),
  retryDownload:id=>ipcRenderer.invoke('download:retry',id),
  showFloatingLyrics:()=>ipcRenderer.invoke('lyrics:open'),
  closeFloatingLyrics:()=>ipcRenderer.invoke('lyrics:close'),
  resetFloatingLyricsPosition:()=>ipcRenderer.invoke('lyrics:reset-position'),
  getFloatingLyricsPosition:()=>ipcRenderer.invoke('lyrics:position'),
  lockFloatingLyrics:locked=>ipcRenderer.invoke('lyrics:lock',locked),
  updateFloatingLyrics:data=>ipcRenderer.invoke('lyrics:update',data),
  floatingLyricsStatus:()=>ipcRenderer.invoke('lyrics:status'),
  lyricsPreferences:()=>ipcRenderer.invoke('lyrics:preferences'),
  previewFloatingLyricsStyle:style=>ipcRenderer.invoke('lyrics:preview-style',style),
  onOpenLyricsSettings:cb=>{const listener=()=>cb();ipcRenderer.on('lyrics:open-settings',listener);return()=>ipcRenderer.removeListener('lyrics:open-settings',listener)},
  onFloatingLyricsStatus:cb=>{const listener=(_e,data)=>cb(data);ipcRenderer.on('lyrics:status',listener);return()=>ipcRenderer.removeListener('lyrics:status',listener)},
  onFloatingLyricsLockStatus:cb=>{const listener=(_e,data)=>cb(data);ipcRenderer.on('lyrics:lock-status',listener);return()=>ipcRenderer.removeListener('lyrics:lock-status',listener)},
  listFavorites:()=>ipcRenderer.invoke('favorites:list'),
  addFavorite:track=>ipcRenderer.invoke('favorites:add',track),
  playFavorite:id=>ipcRenderer.invoke('favorites:play',id),
  removeFavorite:id=>ipcRenderer.invoke('favorites:remove',id),
  retryFavoriteLyrics:id=>ipcRenderer.invoke('favorites:retry-lyrics',id),
  prepareAudio: id => ipcRenderer.invoke('music:prepare', id),
  streamAudio: id => ipcRenderer.invoke('music:stream', id),
  stopOnlinePlayback:()=>ipcRenderer.invoke('music:stop-stream'),
  fetchLyricsMemory:id=>ipcRenderer.invoke('music:lyric-memory',id),
  setPlaybackState:playing=>ipcRenderer.invoke('music:playback-state',!!playing),
  fetchLyrics: id => ipcRenderer.invoke('music:lyric', id),
  playLocal: name => ipcRenderer.invoke('local:play', name),
  cacheStats: () => ipcRenderer.invoke('music:cache-stats'),
  clearCache: () => ipcRenderer.invoke('music:cache-clear'),
  onDownloadTask: cb => {
    const listener=(_e, data)=>cb(data);
    ipcRenderer.on('download:task',listener);
    return ()=>ipcRenderer.removeListener('download:task',listener);
  },
  onProgress: cb => {
    const listener = (_e, text) => cb(text);
    ipcRenderer.on('download:progress',listener);
    return () => ipcRenderer.removeListener('download:progress',listener);
  }
}));
